"""冊E（通し演習）のためにあらたに作る図。

  地域調査の大問には、本番と同じく高校生の会話文が要る。
  会話文もSVGにしておくと、アプリと紙で同じものを見られる。
"""
from figlib import NOTE_MAP, rect, svg, txt

TALK = [
    ("ミナト", "この地形図、川に沿って平らな面が階段みたいに"),
    ("", "並んでいるね。面と面の間は等高線が集まっていて急だ。"),
    ("セリ", "標高点を見ると、川ぞいが41.4m、その一段上が61.3m、"),
    ("", "いちばん上が121.3m。川から離れるほど高くなっている。"),
    ("ミナト", "面ごとに地図記号がちがうよ。川ぞいは田で、"),
    ("", "上の面は畑や茶畑になっている。"),
    ("先生", "なぜでしょうか。高い面は川の水面から離れているので"),
    ("", "（　カ　）のです。だから水を多く必要としない"),
    ("", "（　キ　）などに使われてきました。"),
    ("セリ", "土地の高さのちがいが、そのまま使い方のちがいに"),
    ("", "なっているんですね。"),
]


def talk():
    W = 720
    H = 92 + len(TALK) * 30 + 40
    b = [txt(20, 30, "資料2　地域調査での会話", 16, "start", "bold"),
         rect(20, 46, W - 40, H - 96, "none", 1)]
    y = 78
    for (who, line) in TALK:
        if who:
            b.append(txt(40, y, who, 13, "start", "bold"))
        b.append(txt(118, y, line, 14))
        y += 30
    b.append(txt(20, H - 14, NOTE_MAP, 11))
    return svg(W, int(H), "\n".join(b), "地域調査の会話文")


FIGURES = {"E2_talk.svg": talk}
