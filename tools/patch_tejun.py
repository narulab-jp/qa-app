# -*- coding: utf-8 -*-
"""スマホ設定手順.md に「自分の名前を登録する」の説明を足す（専門用語は使わない）。"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "スマホ設定手順.md")
t = io.open(P, encoding="utf-8-sig").read().replace("\r\n", "\n")
ok = True


def sub(old, new, tag):
    global t, ok
    if old not in t:
        print("★未検出: %s" % tag)
        ok = False
        return
    t = t.replace(old, new, 1)


# 名前の登録を「4. マイクを許可する」の前に入れる
sub("""## 4. マイクを許可する（最初の1回だけ）""",
"""## 4. はじめに自分の名前を登録する

このアプリは、**家族の何人かで使えます。** 記録が混ざらないように、
最初に自分の名前を登録します。

1. 最初に「はじめに、使う人の名前を登録してください。」という画面が出ます
2. 入力欄に **自分の名前**を入れます（「たろう」「長男」など、何でも構いません）
3. **「＋ 新しく追加」** を押します

これで登録は終わりです。次からは、この名前を選ぶだけで始められます。

### 自分の名前が出ているか、毎回たしかめる

登録すると、**画面のいちばん上に「〇〇 として学習中」と出ます。**

```
　┌──────────────────────────┐
　│ たろう として学習中      ［切り替え］ │
　└──────────────────────────┘
```

**ここに出ている名前が自分かどうか、毎回たしかめてください。**
ほかの人の名前が出ていたら、右の **［切り替え］** を押して自分を選びます。

別の人として答えてしまうと、その人の記録に混ざってしまいます。

### 名前を増やす・変える・消す

［切り替え］を押すと、登録した人の一覧が出ます。ここで

- 別の人を選ぶ
- **「＋ 新しく追加」** で人を増やす（何人でも増やせます）
- 名前の右の **「名前」** で名前を変える
- 名前の右の **「削除」** でその人を消す

ができます。

---

## 5. マイクを許可する（最初の1回だけ）""", "名前の登録")

# 以降の見出し番号をずらす
for a, b in [("## 5. 使い方", "## 6. 使い方"),
             ("### 5-1. ふだんの練習は「間違いノート」から",
              "### 6-1. ふだんの練習は「間違いノート」から"),
             ("### 5-2. 単元を選んで解く", "### 6-2. 単元を選んで解く"),
             ("### 5-3. 全問正解するまで終わらない「周回」",
              "### 6-3. 全問正解するまで終わらない「周回」"),
             ("### 5-4. 答え方", "### 6-4. 答え方"),
             ("## 6. 終わったら必ず「保存」する（大事）",
              "## 7. 終わったら必ず「保存」する（大事）"),
             ("## 7. 声が使えないとき", "## 8. 声が使えないとき"),
             ("## 8. 困ったときは", "## 9. 困ったときは"),
             ("## 9. 間違いノートを紙で持ち歩きたいとき",
              "## 10. 間違いノートを紙で持ち歩きたいとき")]:
    sub(a, b, "見出し番号 " + a)

# 保存の説明にファイル名の話を足す
sub("""これを押すと `chiri_note.json` というファイルがダウンロードされます。""",
"""これを押すと、**自分の名前が入ったファイル**がダウンロードされます。

```
たろう さんの場合 → chiri_note_たろう.json
```

名前が入っているので、家族の分がまざりません。""", "ファイル名")

sub("""アプリを開いたら、**まず一番上の「前回のノートを読み込む」を押して、
保存した `chiri_note.json` を選んでください。**""",
"""アプリを開いたら、**まず一番上の「前回のノートを読み込む」を押して、
自分の名前が入ったファイルを選んでください。**（例：`chiri_note_たろう.json`）

**ほかの人のファイルを選ばないように気をつけてください。**
もし違う人のものを選んだときは、

```
このノートは「〇〇」のものです。
今は「△△」として使っています。読み込みますか。
　［〇〇に切り替えて読み込む］　［いいえ（戻る）］
```

と確認が出ます。**自分のものでなければ「いいえ（戻る）」を押してください。**""",
    "読み込みの注意")

# 困ったとき表に1行足す
sub("""| 文字が小さい | トップ画面の「設定」で、文字サイズを「大」にする |""",
"""| 文字が小さい | トップ画面の「設定」で、文字サイズを「大」にする |
| 別の人の名前が出ている | 画面の上の［切り替え］を押して、自分を選ぶ |
| 記録が別の人と混ざった | 自分のファイルを読み込み直す（名前入りのファイルを選ぶ） |""",
    "困ったとき表")

io.open(P, "w", encoding="utf-8", newline="\n").write(t)
print("スマホ設定手順.md: %s" % ("更新しました" if ok else "★未検出あり"))
sys.exit(0 if ok else 1)
