    b.append(line(60, 450, 660, 450, 0.8, "3,3"))
    b.append(txt(20, 512, "実線は平年並み（0.0℃）、破線は0.5℃ごとの等値線。"
                          "＋は平年より高いことを表す。", 12))
    b.append(txt(20, H - 12, NOTE_FAKE, 11))
    return svg(W, H, "\n".join(b), "架空の海域の海面水温平年差図")


