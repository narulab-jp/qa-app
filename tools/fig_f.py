# F2　海面水温の平年差
# ======================================================================
# 架空の海域。東側で平年より高く、西側で低い。等値線は0.5℃ごと。
SST = [
    # (等値線の値, 折れ線の点)
    (1.0, [(430, 150), (470, 210), (480, 300), (455, 380), (415, 430)]),
    (0.5, [(370, 120), (420, 200), (435, 305), (405, 395), (355, 450)]),
    (0.0, [(300, 105), (340, 200), (350, 310), (320, 400), (270, 460)]),
    (-0.5, [(225, 115), (260, 205), (268, 310), (240, 400), (190, 455)]),
]


def sst():
    H = 560
    b = [txt(20, 32, "資料2　架空の海域における海面水温の平年差（℃）", 16,
             "start", "bold"),
         rect(60, 60, 600, 420, "none", 1.4)]
    for v, pts in SST:
        b.append(poly(pts, 1.5 if v == 0.0 else 1.0,
                      "" if v == 0.0 else "5,4"))
        b.append(txt(pts[2][0] + 6, pts[2][1], "%+.1f" % v if v else "0.0", 12))
    # カは -0.5 の線より西、キは 0.0 と +0.5 の間、クは +1.0 の線より東
    b.append(mark(170, 260, "カ"))
    b.append(mark(390, 260, "キ"))
    b.append(mark(560, 260, "ク"))
    b.append(txt(80, 90, "西", 14, "start", "bold"))
    b.append(txt(636, 90, "東", 14, "end", "bold"))
