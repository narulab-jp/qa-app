# F4　主題図3枚の同時比較
# ======================================================================
# 架空の国。4つの州の、3つの指標の高低を階級区分図で示す。
# タ＝人口密度、チ＝1人あたり所得、ツ＝第一次産業就業者の割合
# 3枚が同じ模様にならないようにしてある（同じだと答えが決まらない）。
STATE = [
    # (州名, 図形, 人口密度, 所得, 第一次産業)
    ("Ａ州", [(60, 90), (200, 80), (215, 200), (70, 210)], 3, 3, 1),
    ("Ｂ州", [(200, 80), (330, 95), (340, 205), (215, 200)], 2, 3, 1),
    ("Ｃ州", [(70, 210), (215, 200), (225, 320), (80, 330)], 2, 2, 2),
    ("Ｄ州", [(215, 200), (340, 205), (350, 325), (225, 320)], 1, 1, 3),
]
CLASS = {3: "hatch:diagfine", 2: "hatch:diag", 1: "hatch:dot"}
CLASSNAME = {3: "高い", 2: "中くらい", 1: "低い"}


def theme():
    H = 560
    b = [txt(20, 32, "資料4　架空の国における3つの主題図", 16, "start", "bold")]
    for k, (ttl, idx) in enumerate([("図タ", 2), ("図チ", 3), ("図ツ", 4)]):
        ox = 20 + k * 236
        b.append(txt(ox + 8, 60, ttl, 15, "start", "bold"))
        for (nm, pts, d, inc, prim) in STATE:
            v = (d, inc, prim)[idx - 2]
            p = [(ox + (x - 60) * 0.62, 70 + (y - 80) * 0.62) for (x, y) in pts]
            b.append(poly(p, 1.2, "", CLASS[v], True))
            cx = sum(q[0] for q in p) / 4.0
            cy = sum(q[1] for q in p) / 4.0
            # 州名がハッチにまぎれないよう、下地を白でぬく
            b.append('<rect x="%.1f" y="%.1f" width="34" height="20" '
                     'fill="#fff" stroke="none"/>' % (cx - 17, cy - 10))
            b.append(txt(cx, cy + 5, nm, 13, "middle", "bold"))
    y = 300
    b.append(rect(20, y, W - 40, 62, "none", 1))
    b.append(txt(32, y + 20, "凡例（3枚に共通）", 12, "start", "bold"))
    for k in (3, 2, 1):
        x = 190 + (3 - k) * 170
        b.append(rect(x, y + 6, 26, 18, CLASS[k], 1))
        b.append(txt(x + 32, y + 20, CLASSNAME[k], 13))
    b.append(txt(32, y + 48,
                 "図タ・図チ・図ツは、人口密度・1人あたり所得・"
                 "第一次産業就業者の割合のいずれかである。", 11))
    b.append(txt(20, y + 96, "4つの州について（参考）", 13, "start", "bold"))
    b.append(txt(20, y + 120,
                 "Ａ州には首都があり、Ｂ州は工業がさかんで、", 13))
    b.append(txt(20, y + 142,
                 "Ｃ州は農業を中心とし、Ｄ州は内陸の山がちな州である。", 13))
    b.append(txt(20, H - 12, NOTE_FAKE, 11))
    return svg(W, H, "\n".join(b), "架空の国の主題図3枚")


