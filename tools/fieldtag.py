def field_of(subject, unit_id, seq, section="", skill=""):
    """1問の分野を返す。決まらなければ空文字を返す（黙って埋めない）。"""
    if subject == "chiri":
        return EXC.get((unit_id, section)) or LEC.get(unit_id, "")
    if subject == "chiri-zuhyo":
        if unit_id == "A":
            return A_SKILL.get(skill, "")
        for (a, b), f in ZUHYO_RANGE:
            if a <= seq <= b:
                return f
        return ""
    if subject == "chiri-honban":
        return HONBAN.get(seq, "")
    return ""


def is_prereq(subject, field):
    """A5の前提技能として第1分冊に同居させる問かどうか。"""
    return subject == "chiri-zuhyo" and field == "A1"


def apply(data):
    """科目データ全体に field / priority / prereq を付ける。
       既存のキーは書き換えない。決まらなかった問は一覧にして返す。"""
    subject = data["subjectId"]
    missing = []
    for u in data["units"]:
        for q in u["questions"]:
            f = field_of(subject, u["id"], int(q.get("seq") or 0),
                         q.get("section", ""), q.get("skill", ""))
            if not f:
                missing.append((u["id"], q.get("seq")))
                continue
            q["field"] = f
            q["priority"] = PRIORITY[f]
            # prank は並べ替え用の数値。アプリ側が分野の名まえを知らなくても
            # 優先度の高い順に並べられるよう、ここで数にしておく。
            q["prank"] = PRIORITY_ORDER.index(f) * 10
            if is_prereq(subject, f):
                q["prereq"] = True
                # 前提技能は、それが道具になる A5 のすぐ後ろに置く
                q["prank"] = PRIORITY_ORDER.index("A5") * 10 + 5
    return missing
